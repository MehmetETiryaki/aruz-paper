import argparse
import json
import os
import random
import re
import runpy
import unicodedata
from collections import Counter, defaultdict
from pathlib import Path

import fitz

from aruz.editions import apply_orthography, silent_mark
from aruz.scan import VOWELS, syllabify, weight
from aruz.validate import tokens

ROOT = Path(__file__).resolve().parent.parent

def latoc_converter(work: Path):
    g = runpy.run_path(str(ROOT / "third_party/latoc/2_preprocessing.py"), run_name="latoc")
    g["load_controversy_cache"].__globals__["CONTROVERSY_CACHE_JSON"] = str(work / "YOUR_PATH/controversy_cache.json")
    g["load_controversy_cache"]()
    return g["process_text_with_arabic_marking"], g["get_file_key"]

def marks(line: str, silent: str, context: str = "") -> str:
    sy = [s for w in tokens(apply_orthography(line, silent, context)) if any(c in VOWELS for c in w) for s in syllabify(w)]
    return "".join({"L": "–", "S": "·", "LH": "–·"}[weight(*s)] for s in sy) + f" ({len(sy)})"

def main() -> None:
    store = Path(os.environ["STORE"])
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("books", nargs="+")
    parser.add_argument("--poems", type=int, default=6)
    parser.add_argument("--work", type=Path, default=store / "projects/aruz/latoc")
    parser.add_argument("--pdfs", type=Path, default=store / "datasets/ottoman_poetry/latoc/pdf")
    parser.add_argument("--corpus", type=Path, default=store / "datasets/ottoman_poetry/processed/latoc.jsonl")
    args = parser.parse_args()

    convert, file_key = latoc_converter(args.work)
    recs = [json.loads(l) for l in open(args.corpus, encoding="utf-8")]
    out_dir = ROOT / "docs/reviews"
    out_dir.mkdir(parents=True, exist_ok=True)

    pdfs = {unicodedata.normalize("NFC", p.stem): p for p in args.pdfs.glob("*.pdf")}
    for book in args.books:
        book = unicodedata.normalize("NFC", book)
        random.seed(book)
        mine = [r for r in recs if r["book"] == book]
        if not mine:
            raise SystemExit(f"{book} is not in {args.corpus}")
        doc = fitz.open(pdfs[book])
        key = file_key(f"{book}_layout.json")
        lines = [f"# Review: {book}", "",
                 f"Poet {mine[0]['poet']}, century {mine[0]['century']}, split **{mine[0]['split']}**. "
                 f"Silent marks: `{mine[0]['silent']}`. Generated by `scripts/review_book.py`.", ""]

        glyphs, examples = Counter(), defaultdict(Counter)
        for page in doc:
            for w in page.get_text().split():
                for ch in set(w):
                    if not ch.isascii():
                        glyphs[ch] += 1
                        examples[ch][w] += 1
        lines += ["## Glyphs", "",
                  "Every non-ASCII character of the raw PDF, and what the pipeline turns it into.", "",
                  "| glyph | count | raw → converted |", "|---|---|---|"]
        for ch, n in glyphs.most_common():
            ex = [w for w, _ in examples[ch].most_common(3)]
            shown = "; ".join(f"`{w}` → `{convert(w, key)}`" for w in ex)
            lines.append(f"| `{ch}` U+{ord(ch):04X} {unicodedata.name(ch, '?')} | {n} | {shown} |")

        resolved = defaultdict(Counter)
        for r in mine:
            for u in r["units"]:
                for m in u["misras"]:
                    for w in m.split():
                        for i, c in enumerate(w):
                            if c in "’'":
                                how = ("silent (always)" if c in r["silent"] else
                                       ("silent (context)" if silent_mark(w, i) else "hemze (context)") if c in r["context"]
                                       else "consonant (not listed)")
                                resolved[c, how][w] += 1
        lines += ["", "## Apostrophes", "",
                  f"Silent always: `{mine[0]['silent']}`; by context: `{mine[0]['context']}`.", "",
                  "| mark | read as | count | examples |", "|---|---|---|---|"]
        for (c, how), words in sorted(resolved.items()):
            lines.append(f"| `{c}` | {how} | {sum(words.values())} | {', '.join(f'`{w}`' for w, _ in words.most_common(8))} |")

        units = sum(len(r["units"]) for r in mine)
        usable = sum(u["usable"] for r in mine for u in r["units"])
        lines += ["", "## Summary", "", f"{len(mine)} poems, {units} units, {usable} usable "
                  f"({usable / max(units, 1):.1%}).", ""]

        lines += ["## Sample poems", ""]
        for r in random.sample([r for r in mine if r["units"]], min(args.poems, len(mine))):
            lines += [f"### Poem {r['number']} (page {r['page']}) — `{r['meter_raw']}`", "",
                      f"Patterns allowed: {', '.join(f'`{v}`' for v in r['variants'])}"
                      + (" — vezin inherited from the previous poem" if r["inherited"] else ""), ""]
            for u in r["units"][:4]:
                for m in u["misras"]:
                    lines.append(f"- {u['n']}. {m}  \n  `{marks(m, r['silent'], r['context'])}`")
                if u["issues"]:
                    lines.append(f"  - issues: {', '.join(u['issues'])}{'' if u['usable'] else ' — **not usable**'}")
            raw = [l for l in doc[r["page"] - 1].get_text().splitlines() if l.strip()]
            lines += ["", "<details><summary>raw PDF text of the page</summary>", "", "```"] + raw[:40] + ["```", "</details>", ""]

        lines += ["## Issue examples", ""]
        by_issue = defaultdict(list)
        for r in mine:
            for u in r["units"]:
                for i in u["issues"]:
                    by_issue[re.sub(r"\d+ mısras where the poem has \d+", "wrong mısra count", i)].append((r, u))
        for issue, hits in sorted(by_issue.items(), key=lambda x: -len(x[1])):
            lines += [f"### {issue} ({len(hits)})", ""]
            for r, u in random.sample(hits, min(3, len(hits))):
                vezin = r['variants'][0] if r['variants'] else 'no vezin in the edition'
                lines.append(f"- poem {r['number']} p{r['page']} `{vezin}` unit {u['n']}:")
                for m in u["misras"][:4]:
                    lines.append(f"  - {m} — `{marks(m, r['silent'], r['context'])}`")
            lines.append("")

        path = out_dir / f"{book}.md"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {path}")

if __name__ == "__main__":
    main()
